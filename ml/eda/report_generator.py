import json
from pathlib import Path
from typing import Dict, Any
from ml.utils.logger import logger
from ml.configs import LOGS_DIR

class EDAReportGenerator:
    """
    Automated Professional EDA Report Generator.
    Exports structured JSON reports and human-readable Markdown/HTML audit documents
    for enterprise data science teams and MLOps compliance.
    """
    def __init__(self, output_dir: Path = LOGS_DIR):
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def export_report(self, eda_data: Dict[str, Any], filename_prefix: str = "enterprise_eda") -> Dict[str, str]:
        """Exports JSON and Markdown EDA reports to disk."""
        logger.info(f"Exporting professional EDA reports with prefix '{filename_prefix}'...")
        
        # 1. Export JSON
        json_path = self.output_dir / f"{filename_prefix}_report.json"
        try:
            with open(json_path, 'w', encoding='utf-8') as f:
                json.dump(eda_data, f, indent=2, default=str)
            logger.info(f"JSON EDA report saved to {json_path}")
        except Exception as e:
            logger.error("Failed to save JSON EDA report", exc_info=e)
            
        # 2. Generate Professional Markdown Report
        md_path = self.output_dir / f"{filename_prefix}_report.md"
        summary = eda_data.get("summary", {})
        boxplots = eda_data.get("boxplots", {})
        distributions = eda_data.get("distributions", {})
        missing = eda_data.get("missing_heatmap", {})
        
        md_content = [
            f"# Enterprise Automated EDA Report: {summary.get('dataset_name', 'Dataset')}",
            "\n## 1. Executive Summary & Health Diagnostics",
            f"* **Total Observations (Rows)**: {summary.get('total_rows', 0):,}",
            f"* **Total Features (Columns)**: {summary.get('total_columns', 0)}",
            f"* **Global Missing Value Ratio**: {summary.get('missing_percentage_global', 0)}%",
            f"* **Duplicate Rows**: {summary.get('duplicate_rows', 0):,}",
            f"* **Memory Usage**: {summary.get('memory_usage_mb', 0)} MB",
            "\n### Data Types Breakdown",
            f"* **Numerical Features**: {summary.get('dtypes_breakdown', {}).get('numerical', 0)}",
            f"* **Categorical Features**: {summary.get('dtypes_breakdown', {}).get('categorical', 0)}",
            f"* **DateTime Features**: {summary.get('dtypes_breakdown', {}).get('datetime', 0)}",
            "\n## 2. Missing Value Heatmap Analysis"
        ]
        
        if missing:
            md_content.append("| Feature Name | Missing Cells | Percentage |")
            md_content.append("| :--- | :---: | :---: |")
            total_rows = max(1, summary.get('total_rows', 1))
            for col, count in missing.items():
                pct = round((count / total_rows) * 100, 2)
                md_content.append(f"| `{col}` | {count:,} | {pct}% |")
        else:
            md_content.append("*No missing values detected across the entire dataset!*")
            
        md_content.append("\n## 3. Numerical Distribution & Outlier Diagnostics")
        md_content.append("| Feature | Mean | Std Dev | Median | IQR | Outliers Detected | Outlier % |")
        md_content.append("| :--- | :---: | :---: | :---: | :---: | :---: | :---: |")
        
        for col, dist in distributions.items():
            box = boxplots.get(col, {})
            md_content.append(
                f"| `{col}` | {dist.get('mean')} | {dist.get('std')} | {dist.get('median')} | "
                f"{box.get('iqr')} | {box.get('outliers_detected', 0):,} | {box.get('outlier_percentage', 0)}% |"
            )
            
        md_content.append("\n## 4. Time Series & Temporal Trends")
        ts_trends = eda_data.get("time_series_trends", {})
        if ts_trends:
            drange = ts_trends.get("date_range", {})
            md_content.append(f"* **Date Horizon**: {drange.get('start', 'N/A')} to {drange.get('end', 'N/A')} ({drange.get('total_days', 0)} days)")
            md_content.append("* **Trend Status**: Continuous temporal tracking active across revenue and sales volume.")
        else:
            md_content.append("*No explicit chronological date column detected for time-series aggregation.*")
            
        md_content.append("\n---")
        md_content.append("*Report automatically generated by Amazon-AI Enterprise MLOps Engine.*")
        
        try:
            with open(md_path, 'w', encoding='utf-8') as f:
                f.write("\n".join(md_content))
            logger.info(f"Markdown EDA report saved to {md_path}")
        except Exception as e:
            logger.error("Failed to save Markdown EDA report", exc_info=e)
            
        return {
            "json_report": str(json_path),
            "markdown_report": str(md_path)
        }
